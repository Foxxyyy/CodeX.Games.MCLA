    //scrThread::Register (sub_82554798) plus the VM's own built-ins registered in
    //sub_82556C18. A compiled .sco only carries the hash of a native, so this table is what
    //turns a call site back into a name - it covers every hash the shipped scripts call.
    //
    //The hash is sub_82557F78: the RAGE filename hash (Jenkins one-at-a-time over the
    //lowercased name, backslashes folded to slashes), bumped to 2 when it comes out below that.
    public static class ScoNatives
    {
        private static Dictionary<uint, string> _byHash;

        public static uint Hash(string name)
        {
            uint h = 0;
            foreach (var ch in name)
            {
                var c = char.ToLowerInvariant(ch == (char)92 ? '/' : ch); //backslashes fold to slashes
                h += c;
                h += h << 10;
                h ^= h >> 6;
            }
            h += h << 3;
            h ^= h >> 11;
            h += h << 15;
            return h < 2 ? h + 2 : h;
        }

        public static string Lookup(uint hash)
        {
            var map = _byHash;
            if (map == null)
            {
                map = new Dictionary<uint, string>(Names.Length);
                foreach (var n in Names) map[Hash(n)] = n;
                _byHash = map;
            }
            return map.TryGetValue(hash, out var name) ? name : null;
        }

